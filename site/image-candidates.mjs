// Finds public-domain image candidates on Wikimedia Commons for timeline entries.
//   node image-candidates.mjs OUT.json [--limit N] [--imp 1,2]
// For each branch and event (by default imp 1–2), searches Commons files by the entry's title and keeps only files
// whose Commons license metadata is public domain or CC0, that are not in any AI-generated category, and whose
// recorded date (if any) is before 2020. Requests go one at a time with a pause, and results are cached in
// .image-cache.json so the script can be stopped and restarted.
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { execFileSync } from "node:child_process";

const here = path.dirname(new URL(import.meta.url).pathname);
const out = process.argv[2];
const arg = (k, d) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : d; };
const limit = +arg("--limit", 1e9), imps = arg("--imp", "1,2").split(",").map(Number);
const cacheFile = path.join(here, ".image-cache.json");
const cache = fs.existsSync(cacheFile) ? JSON.parse(fs.readFileSync(cacheFile, "utf8")) : {};
const entries = [];
for (const f of fs.readdirSync(path.join(here, "data")).filter((f) => f.endsWith(".js")).sort()) {
  vm.runInNewContext(fs.readFileSync(path.join(here, "data", f), "utf8"), { TL: {
    add(o) { for (const b of o.branches || []) entries.push({ id: b.id, kind: "branch", q: b.name, y: b.start, text: b.text });
             for (const e of o.events || []) if (imps.includes(e.imp)) entries.push({ id: e.id, kind: "event", q: e.title, y: e.y, text: e.text }); },
    cite() {}, enrich() {}, geo() {}, image() {}, origin() {}, move() {}, patch() {}, merge() {} } });
}
const UA = "history-timeline-builder/1.0 (offline educational timeline; public-domain image search)";
const sleep = (s) => execFileSync("sleep", [String(s)]);
// Returns parsed JSON, or null after repeated failures. A 429 (rate limit) waits progressively longer and is
// never cached as "no results", so a later run picks the entry up again.
function get(url) {
  for (let a = 0; a < 8; a++) {
    let out = "";
    try { out = execFileSync("curl", ["-sS", "--max-time", "40", "-A", UA, "-w", "\n%{http_code}", url], { encoding: "utf8" }); } catch {}
    const code = out.slice(out.lastIndexOf("\n") + 1), body = out.slice(0, out.lastIndexOf("\n"));
    if (code === "200") { try { return JSON.parse(body); } catch {} }
    sleep(code === "429" ? 30 * (a + 1) : 6 * (a + 1));
  }
  return null;
}
const strip = (h) => String(h || "").replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim();
const PD = /^(public domain|pd|cc0)/i;
const results = {};
let n = 0;
for (const e of entries) {
  if (n >= limit) break;
  if (!(e.id in cache)) {
    const q = e.q.replace(/[“”"]/g, "").slice(0, 80);
    const url = "https://commons.wikimedia.org/w/api.php?action=query&format=json&generator=search&gsrnamespace=6&gsrlimit=12" +
      "&gsrsearch=" + encodeURIComponent(q + " -fileres:0") +
      "&prop=imageinfo|categories&cllimit=50&iiprop=url|size|mime|extmetadata&iiurlwidth=480" +
      "&iiextmetadatafilter=LicenseShortName|Artist|DateTimeOriginal|ImageDescription|ObjectName|Credit";
    const j = get(url);
    if (!j) { console.log(`\n✗ gave up on ${e.id} (will retry on the next run)`); continue; }
    const cands = [];
    for (const p of Object.values(j?.query?.pages || {})) {
      const ii = p.imageinfo?.[0]; if (!ii || !/^image\/(jpeg|png|gif|tiff|webp)/.test(ii.mime)) continue;
      const md = ii.extmetadata || {}, lic = strip(md.LicenseShortName?.value);
      const cats = (p.categories || []).map((c) => c.title.replace(/^Category:/, ""));
      if (!PD.test(lic)) continue;
      if (cats.some((c) => /AI[- ]generated|generated by (AI|artificial)|Midjourney|DALL|Stable Diffusion/i.test(c))) continue;
      const dateStr = strip(md.DateTimeOriginal?.value), yr = +((dateStr.match(/\b(1\d{3}|20\d{2})\b/) || [])[1] || 0);
      if (yr >= 2020) continue;
      cands.push({ file: p.title, thumb: ii.thumburl, w: ii.thumbwidth, h: ii.thumbheight, page: ii.descriptionurl,
        license: lic, artist: strip(md.Artist?.value).slice(0, 160), date: dateStr.slice(0, 60),
        desc: strip(md.ImageDescription?.value || md.ObjectName?.value).slice(0, 300), cats: cats.slice(0, 12) });
    }
    cache[e.id] = cands.slice(0, 6);
    fs.writeFileSync(cacheFile, JSON.stringify(cache));
    n++; process.stdout.write(`  ${n} searched (${e.id})\x1b[K\r`);
    sleep(3);
  }
  if (cache[e.id]?.length) results[e.id] = { kind: e.kind, title: e.q, y: e.y, text: e.text, candidates: cache[e.id] };
}
fs.writeFileSync(out, JSON.stringify(results, null, 1));
console.log(`\n${Object.keys(results).length} of ${entries.length} entries have public-domain candidates → ${out}`);
